export const FONT_CHARS = Object.keys(G).join('');
export const FONT_COLS = 16;

/** Draws the font atlas (white glyphs with a 1px dark outline) into a canvas. */
export function drawFontCanvas(outline = '#1e1b2e'): HTMLCanvasElement {
  const chars = FONT_CHARS;
  const rows = Math.ceil(chars.length / FONT_COLS);
  const c = document.createElement('canvas');
  c.width = FONT_COLS * CELL_W;
  c.height = rows * CELL_H;
  const ctx = c.getContext('2d')!;
  for (let i = 0; i < chars.length; i++) {
    const glyph = G[chars[i]!]!;
    const ox = (i % FONT_COLS) * CELL_W + 1;
    const oy = Math.floor(i / FONT_COLS) * CELL_H + 1;
    ctx.fillStyle = outline;
    for (let y = 0; y < GLYPH_H; y++)
      for (let x = 0; x < GLYPH_W; x++)
        if (glyph[y]![x] === '#')
          for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) ctx.fillRect(ox + x + dx, oy + y + dy, 1, 1);
    ctx.fillStyle = '#ffffff';
    for (let y = 0; y < GLYPH_H; y++) for (let x = 0; x < GLYPH_W; x++) if (glyph[y]![x] === '#') ctx.fillRect(ox + x, oy + y, 1, 1);
  }
  return c;
}
